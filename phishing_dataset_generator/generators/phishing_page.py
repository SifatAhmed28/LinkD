"""
Phishing page generator with dual hosting modes.

Supports two phishing hosting scenarios:
  1. Third-party hosted: page deployed on trusted platforms (facebook.github.io)
  2. Attacker-owned domain: page on typosquatting/combosquatting domains (faceb00k.com)

Both modes apply a social engineering variation strategy on top of the base page.
"""

import random

from . import html_builder
from .template_loader import load_and_build
from .phishing_variations import apply_variation, pick_strategy
from .attacker_domains import generate_attacker_domain, pick_attacker_strategy
from .legit_phish_utility import classify_form_action, hostname, belongs_to_domain, generate_platform_url, URL_PATH_PHRASES, FAKE_DOMAINS_PHRASES, generate_random_combo, get_tld_risk

def generate_phishing_page(
    brand_key: str,
    brand: dict,
    platform_name: str | None = None,
    platform_domain: str | None = None,
    hidden_field_count: int = 2,
    strategy: str | None = None,
    hosting_mode: str = "third_party",
    index: int = 0,
    has_saved_template: bool = False,
    template_dir: str = "",
    brands_meta: dict | None = None,
) -> tuple[str, dict]:
    """
    Generate a phishing page with a social engineering variation.

    Args:
        brand_key: Brand key (e.g., "google").
        brand: Brand metadata dict from html_builder.BRANDS.
        platform_name: Platform display name (e.g., "github_io").
        platform_domain: Platform domain (e.g., "github.io").
        hidden_field_count: Number of hidden tracking fields to inject.
        strategy: Phishing strategy to apply. If None, picks randomly.
        hosting_mode: "third_party" (facebook.github.io) or "first_party" (faceb00k.com).
        index: Page index for filename generation.
        has_saved_template: Whether a saved HTML template exists for this brand.
        template_dir: Path to templates/brands/ directory.
        brands_meta: Brand metadata from brands_meta.yaml (for template fallback).

    Returns:
        (html_string, metadata_dict)
    """
    # Pick strategy if not specified
    if strategy is None:
        strategy = pick_strategy()

    # ── Generate hosting-specific URL and domain ──────────────────────────
    attacker_meta = None
    tld_risk_score = 0

    if hosting_mode == "first_party":
        # Attacker-owned domain: typosquatting, combosquatting, etc.
        attacker_domain, attacker_meta = generate_attacker_domain(brand_key)
        page_host = attacker_domain

        # Reuse the path generated by attacker_domains.py.
        url_path = attacker_meta["url_path"]

        # generates form action url for attacker owned domains
        form_path = generate_random_combo(URL_PATH_PHRASES)
        form_action_url = f"https://{page_host}{form_path}"
    elif hosting_mode == "third_party":
        if not platform_domain:
            raise ValueError("platform_domain is required for third_party phishing")
        # Third-party hosted: attacker-controlled tenant on a shared platform.
        form_action_url = _generate_phishing_action_url(platform_domain)
        subdomain = generate_random_combo(FAKE_DOMAINS_PHRASES, "domain")
        page_host = f"{subdomain}.{platform_domain}"
        # generates page url path
        url_path = generate_random_combo(URL_PATH_PHRASES)
        # extract tld for tld risk score
        tld = platform_domain.split(".")[-1]
        tld_risk_score = get_tld_risk(tld)
    else:
        raise ValueError(
            f"Invalid hosting_mode: {hosting_mode!r}. "
            "Expected 'first_party' or 'third_party'."
        )
    # generates Page url
    page_url = f"https://{page_host}{url_path}"

    # ── Generate hidden fields (only for third-party hosted) ──────────────
    if hosting_mode == "third_party":
        hidden_fields_html = _generate_hidden_fields(hidden_field_count, platform_domain)
    else:
        # Attacker-owned domains also use hidden fields for tracking
        hidden_fields_html = _generate_hidden_fields(hidden_field_count, page_host)

    # ── Build base HTML ───────────────────────────────────────────────────
    # Screenshot overlay strategy replaces the entire page — no variation injection needed
    if strategy == "screenshot_overlay":
        final_html, raster_meta = html_builder.build_screenshot_overlay_page(
            brand, form_action_url, hidden_fields_html, page_host
        )
        variation_meta = {
            "phishing_strategy": strategy,
            "urgency_text_injected": False,
            "authority_text_injected": False,
            "fear_text_injected": False,
            "reward_text_injected": False,
            "document_fields_injected": False,

            # Ground-truth provenance only. Exclude all annotation_* columns
            # from model inputs because they directly reveal the generator path.
            "annotation_visual_modality": "raster_image_overlay",
            "annotation_visible_text_location": "image_pixels",
            "annotation_requires_visual_analysis": True,
            "raster_text_ground_truth": raster_meta["raster_text_ground_truth"],
        }
        return _build_phishing_metadata(
            final_html, variation_meta, brand, brand_key,
            hosting_mode, platform_name, platform_domain,
            form_action_url, "", hidden_field_count,
            page_url, url_path, attacker_meta, tld_risk_score,
        )

    if hosting_mode == "third_party" and has_saved_template and template_dir and brands_meta:
        try:
            brand_meta_yaml = brands_meta.get(brand_key)
            if brand_meta_yaml:
                base_html, _ = load_and_build(
                    template_dir=template_dir,
                    brand_meta=brand_meta_yaml,
                    platform_domain=platform_domain,
                    is_phishing=True,
                    hidden_field_count=hidden_field_count,
                )
            else:
                base_html = html_builder.build_login_page(brand, form_action_url, hidden_fields_html, page_host)
        except Exception:
            base_html = html_builder.build_login_page(brand, form_action_url, hidden_fields_html, page_host)
    else:
        base_html = html_builder.build_login_page(brand, form_action_url, hidden_fields_html, page_host)

    # ── Apply phishing variation strategy ─────────────────────────────────
    final_html, variation_meta = apply_variation(base_html, strategy, brand.get("name", "your"))

    return _build_phishing_metadata(
        final_html, variation_meta, brand, brand_key,
        hosting_mode, platform_name, platform_domain,
        form_action_url, "", hidden_field_count,
        page_url, url_path, attacker_meta, tld_risk_score,
    )


def _build_phishing_metadata(
    final_html: str, variation_meta: dict, brand: dict, brand_key: str,
    hosting_mode: str, platform_name: str, platform_domain: str,
    form_action_url: str, form_action_type: str, hidden_field_count: int,
    page_url: str, url_path: str, attacker_meta: dict | None,
    tld_risk_score: float | None = None,
) -> tuple[str, dict]:
    """Build the metadata dict for a phishing page."""
    real_domain = brand["real_domains"][0] if brand.get("real_domains") else "unknown"

    
    form_action_type = classify_form_action(
        page_url=page_url,
        form_action_url=form_action_url,
        platform_domain=platform_domain,
        resolved_real_domain=real_domain,
    )

    action_host = hostname(form_action_url)
    has_domain_mismatch = not belongs_to_domain(action_host, real_domain)

    metadata = {
        **(attacker_meta or {}),
        
        "label": 1,
        "url": page_url,
        "url_path": url_path,
        
        "hosting_mode": hosting_mode,
        "platform": platform_name,
        "platform_domain": platform_domain,
        "brand": brand.get("name", brand_key),
        "real_domain": real_domain,
     
        "form_action": form_action_url,
        "form_action_type": form_action_type,
        "has_domain_mismatch": has_domain_mismatch,
        "hidden_fields_count": hidden_field_count,
        
        **variation_meta,
    }

    # Ensure third-party pages also carry a TLD risk score
    if tld_risk_score is not None and "tld_risk_score" not in metadata:
        metadata["tld_risk_score"] = tld_risk_score

    return final_html, metadata


# ── Helpers ────────────────────────────────────────────────────────────────────


HIDDEN_FIELD_TEMPLATES = [
    ('redirect', 'https://{platform}/dashboard'),
    ('continue', 'https://{platform}/welcome'),
    ('_next', '/account'),
    ('source', 'email_campaign'),
    ('ref', '{token}'),
    ('ts', '{timestamp}'),
    ('session_id', '{token}'),
    ('flow_id', '{token}'),
    ('context', 'web_login'),
    ('service', 'account'),
]


def _rand_token(length: int = 32) -> str:
    return ''.join(random.choices('abcdef0123456789', k=length))


def _generate_phishing_action_url(platform_domain: str) -> str:
    return generate_platform_url(platform_domain)


def _generate_hidden_fields(count: int, platform_domain: str) -> str:
    if count <= 0:
        return ""

    fields = []
    used_names: set[str] = set()

    for _ in range(count):
        name, value_tmpl = random.choice(HIDDEN_FIELD_TEMPLATES)
        attempts = 0
        while name in used_names and attempts < 20:
            name, value_tmpl = random.choice(HIDDEN_FIELD_TEMPLATES)
            attempts += 1
        used_names.add(name)

        value = value_tmpl.format(
            platform=platform_domain,
            token=_rand_token(24),
            timestamp=str(random.randint(1700000000, 1800000000)),
        )
        fields.append(f'    <input type="hidden" name="{name}" value="{value}">')

    return "\n".join(fields)
